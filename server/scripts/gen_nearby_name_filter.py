"""Writes the chat filter's word list, and the answers the server's filter
gives on a fixed case list, into the web app, so a nearby host (which has no
server) refuses the same names the online server does.

    python scripts/gen_nearby_name_filter.py          # rewrite both files
    python scripts/gen_nearby_name_filter.py --check  # exit 1 if either is stale

``chat_filter_words.txt`` stays the one source; the web copies are derived
from it. ``web/src/offline/server/nearby/chatFilter.test.ts`` checks the web
filter against the cases, and ``tests/test_chat_filter.py`` runs ``--check``.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "server"))

from shengji.api import chat_filter  # noqa: E402

OUT_DIR = ROOT / "web" / "src" / "offline" / "server" / "nearby"
WORDS_OUT = OUT_DIR / "chatFilterWords.gen.ts"
CASES_OUT = OUT_DIR / "chatFilterCases.gen.json"

# Inputs beyond the list's own entries: each rule the filter has (whole
# words, leetspeak, repeats, endings, standalone and not-followed-by Chinese
# phrases, mixed scripts, spacing) and the ordinary words it must not touch.
EXTRA_INPUTS = [
    "fuck you", "FUCK", "Fuuuuuck this", "sh1t happens", "what an a$$hole", "@ss",
    "$h1t", "shitty play", "fucking hell", "you bitches", "gg, fuck!", "fuck你",
    "stfu sb", "class", "assassin", "Scunthorpe", "cockpit", "cocktail", "passage",
    "glass", "assess", "assist", "Sussex", "spicy", "dickens", "therapist", "grape",
    "analysis", "hancock", "skyscraper", "shitake", "Fukushima", "bass", "pass",
    "hello", "hell", "damn", "nice hand", "gg", "2023", "1337", "45s", "455",
    "wait 45s", "你个傻逼", "他妈的", "他媽的又输了", "操你妈", "操！", "我操了", "傻B",
    "草泥马", "体操", "操作", "曹操", "我操作一下", "节操", "妈妈的牌", "今日你来吗",
    "加油", "好牌", "  fuck,  shit.  ", "Player 2", "Jerry", "小明", "Ünïcödé",
    "x fuckface y", "sh!t", "f u c k", "dickhead", "Dick", "ASS", "a s s",
    "emoji 😀 fuck 😀", "😀操😀", "İstanbul", "ΣΊΣΥΦΟΣ",
]


_TO_LEET = str.maketrans({"o": "0", "i": "1", "e": "3", "a": "@", "s": "$"})


def _inputs() -> list[str]:
    seen: dict[str, None] = {}
    for raw in chat_filter.WORDS_FILE.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        word = line.lstrip("=").rstrip("*").partition("!")[0]
        seen[word] = None
        seen[word.upper()] = None
        seen[f"the {word} here"] = None
        seen[word.translate(_TO_LEET)] = None
        if line.endswith("*"):
            seen[word + "ing"] = None
            seen[word + "s"] = None
        if "!" in line:
            for after in line.partition("!")[2]:
                seen[word + after] = None
        if line.startswith("="):
            seen["体" + word] = None
    for text in EXTRA_INPUTS:
        seen[text] = None
    return list(seen)


def render() -> tuple[str, str]:
    words = chat_filter.WORDS_FILE.read_text(encoding="utf-8")
    words_ts = (
        "// Generated by server/scripts/gen_nearby_name_filter.py from\n"
        "// server/shengji/api/chat_filter_words.txt; do not edit by hand.\n"
        f"export const CHAT_FILTER_WORDS = {json.dumps(words, ensure_ascii=False)};\n"
    )
    cases = [{"text": t, "mask": chat_filter.mask(t), "contains": chat_filter.contains(t)}
             for t in _inputs()]
    cases_json = json.dumps(cases, ensure_ascii=False, indent=1) + "\n"
    return words_ts, cases_json


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if a web copy is stale")
    args = ap.parse_args(argv)
    words_ts, cases_json = render()
    targets = [(WORDS_OUT, words_ts), (CASES_OUT, cases_json)]
    if args.check:
        stale = [p for p, text in targets if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}; run server/scripts/gen_nearby_name_filter.py")
        return 1 if stale else 0
    for p, text in targets:
        p.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
