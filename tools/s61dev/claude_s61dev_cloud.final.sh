hold_guard () { [ ! -e "$HOLD" ] && [ ! -L "$HOLD" ] || die "HOLD file $HOLD exists"; }
deadline_guard () { [ $(( SECONDS - WAIT_START )) -lt "$WAIT_CEILING" ] || die "wait ceiling ($WAIT_CEILING s) reached $1; nothing started"; }
