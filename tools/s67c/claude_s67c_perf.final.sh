# --- waits (rule 3: every turn guarded; rule 6: the deadline re-checked on LEAVING every wait) ----------------------
wait_release () { until release_present; do wait_guarded "without RELEASE"; done; deadline_guard "as RELEASE arrived"; hold_guard; release_ok; }
# Releasing a lock DIRECTORY that has contents is not a no-op: rmdir fails on a non-empty directory, and a suppressed
# failure leaves the lock standing forever, blocking every later job on this host (Codex, 2026-09-23).  So remove the
# owner file -- only if it is OURS -- and say so loudly if the rmdir still fails.  Rule 5: nothing not ours is touched.
release_locks () {
  if [ "$LEGACY_OWNED" -eq 1 ]; then
    rmdir "$LEGACY" 2>/dev/null || say "WARNING: could not release the legacy marker $LEGACY; it still holds: $(ls -A "$LEGACY" 2>/dev/null | tr "\n" " ")"
  fi
  if [ "$HOST_OWNED" -eq 1 ]; then
    if [ -f "$HOSTLOCK/owner" ] && [ "$(head -1 "$HOSTLOCK/owner" | cut -d" " -f1)" = "$$" ]; then rm -f "$HOSTLOCK/owner"; fi
    rmdir "$HOSTLOCK" 2>/dev/null || say "WARNING: could not release $HOSTLOCK; it still holds: $(ls -A "$HOSTLOCK" 2>/dev/null | tr "\n" " ")"
  fi
}
# S17 HANDSHAKE (perf; Jerry 2026-10-15/16: the screen runs on perf by pausing the S17 training run, which stays paused for screens
# overnight).  The S17 driver holds the host lock for hours and yields it only to a pause request; it resumes on a marker strictly newer
# than the request.  OWNERSHIP (Codex HOLDs #707 6206524421, 6206903898, 6207655921): the request is a shared file and a marker write can
# never be made atomic with the live driver's observation, so:
#   - this lane NEVER writes the resume marker.  At EXIT (success, REFUSING, ABORT: every path through lane_exit) it writes the handoff
#     file $S17_HANDOFF (its request token, its terminal status line, the exact manual command) and says "S17 left PAUSED by <lane>;
#     resume by hand": the pause owner resumes S17 when the perf queue is empty;
#   - s17_pause REFUSES an OUTSTANDING request (present and not acknowledged by a newer marker) unless it is the pause of an ENDED lane:
#     the request's content equals the token recorded in a handoff file whose lane's status shows a terminal line (LANE DONE / REFUSING /
#     ABORT).  Then it ADOPTS that pause (no new request written; the token and st_mtime_ns taken over) and proceeds to the host-lock
#     wait.  A running lane's pause (no terminal line), a handoff whose token differs from the request, or a request with no handoff
#     refuses.  A stale request (already acknowledged) is replaced by this lane's own token (random nonce, st_mtime_ns recorded).
#   - nothing is ever removed: not the request, not the marker, not any handoff file.  Independent markers (hold/request files inside
#     the host-lock dir, which the driver also honours) are never touched: release_locks removes only this lane's own owner file and
#     rmdir refuses a non-empty lock dir.
s17_mtime_ns () { "$PY" -c 'import os, sys; print(os.stat(sys.argv[1]).st_mtime_ns)' "$1"; }
s17_outstanding () { [ -e "$S17_PAUSE" ] && { [ ! -e "$S17_RESUME" ] || [ ! "$S17_RESUME" -nt "$S17_PAUSE" ]; }; }
s17_ended_lane_handoff () {   # prints the handoff file of an ENDED lane whose recorded token equals the current request; 1 if none
  local h tok st
  for h in "$LANE_ROOT"/claude-s17-handoff.*; do
    [ -f "$h" ] && [ ! -L "$h" ] || continue
    tok=$(sed -n 's/^token: //p' "$h" | head -n 1); st=$(sed -n 's/^status: //p' "$h" | head -n 1)
    [ -n "$tok" ] && [ "$tok" = "$(cat "$S17_PAUSE" 2>/dev/null)" ] || continue
    [ -n "$st" ] && [ -f "$st" ] && [ ! -L "$st" ] && grep -qE 'LANE DONE|REFUSING|ABORT' "$st" || continue
    echo "$h"; return 0
  done
  return 1
}
s17_pause () {
  local h
  [ ! -L "$S17_PAUSE" ] && [ ! -L "$S17_RESUME" ] && [ ! -L "$S17_HANDOFF" ] || die "$S17_PAUSE, $S17_RESUME or $S17_HANDOFF is a symlink"
  if s17_outstanding; then
    h=$(s17_ended_lane_handoff) || die "an S17 pause request is already OUTSTANDING and is not an ended lane's ($S17_PAUSE, mtime $(stat -c %y "$S17_PAUSE" 2>/dev/null), content '$(head -c 200 "$S17_PAUSE" 2>/dev/null)'); not adopting another owner's pause; nothing started"
    S17_TOKEN=$(cat "$S17_PAUSE"); S17_REQ_NS=$(s17_mtime_ns "$S17_PAUSE") || die "could not stat $S17_PAUSE"
    S17_ADOPTED=$(sed -n 's/^lane: //p' "$h" | head -n 1); S17_PAUSED=1; trap lane_exit EXIT
    say "$LANE: adopting the paused S17 from ${S17_ADOPTED:-?} (handoff $h, its status shows a terminal line; request token '$S17_TOKEN', mtime_ns $S17_REQ_NS); no new request written; owner now: $(cat "$HOSTLOCK/owner" 2>/dev/null)"
    return 0
  fi
  S17_TOKEN="$$ $LANE $SELF_SHA $(date -u +%FT%TZ) nonce=$("$PY" -c 'import secrets; print(secrets.token_hex(16))')" || die "could not draw the S17 request nonce"
  printf '%s\n' "$S17_TOKEN" > "$S17_PAUSE" || die "could not write the S17 pause request $S17_PAUSE"
  S17_REQ_NS=$(s17_mtime_ns "$S17_PAUSE") || die "could not stat $S17_PAUSE"
  S17_PAUSED=1; trap lane_exit EXIT
  [ "$(cat "$S17_PAUSE" 2>/dev/null)" = "$S17_TOKEN" ] || die "the S17 pause request was replaced while being written (now '$(head -c 200 "$S17_PAUSE" 2>/dev/null)')"
  say "$LANE: S17 pause requested ($S17_PAUSE token '$S17_TOKEN', mtime_ns $S17_REQ_NS; the driver stops its trainer at the next buffer and releases the host lock; owner now: $(cat "$HOSTLOCK/owner" 2>/dev/null))"
}
s17_mine () { [ -f "$S17_PAUSE" ] && [ ! -L "$S17_PAUSE" ] && [ "$(cat "$S17_PAUSE" 2>/dev/null)" = "$S17_TOKEN" ] && [ "$(s17_mtime_ns "$S17_PAUSE" 2>/dev/null)" = "$S17_REQ_NS" ]; }
s17_resume () {   # EXIT: writes NO resume marker; hands the paused S17 off to its owner
  local mine term
  [ "$S17_PAUSED" -eq 1 ] || return 0
  mine=$(s17_mine && echo "still this lane's" || echo "REPLACED by another actor (now '$(head -c 200 "$S17_PAUSE" 2>/dev/null || echo absent)')")
  term=$(grep -E 'LANE DONE|REFUSING|ABORT' "$S" 2>/dev/null | tail -n 1); [ -n "$term" ] || term="(no terminal line in $S yet: exiting from $(tail -n 1 "$S" 2>/dev/null | cut -c1-160))"
  if [ -L "$S17_HANDOFF" ]; then say "$LANE: S17 left PAUSED by $LANE; the handoff $S17_HANDOFF is a symlink, not written; resume by hand when the perf queue is empty: touch $S17_RESUME"; return 0; fi
  printf 'lane: %s\npid: %s\nlauncher_sha256: %s\ntoken: %s\nrequest_mtime_ns: %s\nrequest_at_exit: %s\nadopted_from: %s\nstatus: %s\nterminal: %s\nresume_by_hand: touch %s\nwritten: %s\n' \
    "$LANE" "$$" "$SELF_SHA" "$S17_TOKEN" "$S17_REQ_NS" "$mine" "${S17_ADOPTED:-none}" "$S" "$term" "$S17_RESUME" "$(date -u +%FT%TZ)" > "$S17_HANDOFF" \
    || say "WARNING: could not write the handoff $S17_HANDOFF"
  say "$LANE: S17 left PAUSED by $LANE (request token '$S17_TOKEN', $mine; terminal: $term; handoff $S17_HANDOFF); resume by hand when the perf queue is empty: touch $S17_RESUME"
}
lane_exit () { release_locks; s17_resume; }
# START GATE (rule 1): ONE SHARED HOST LOCK.  Every job on this host -- screen, corpus store, duel, launcher -- takes
# THIS ONE lock, atomically.  Reading a peer's lock and then taking your own is NOT mutual exclusion: between the read
# and the mkdir the peer can take its lock and both start.  A single contended lock has no such window.  Arbitration
# is START-TIME ONLY (rule 2): the loser waits for the winner to exit, nothing preempts anything.
take_host_lock () {
  local noted=0
  until mkdir "$HOSTLOCK" 2>/dev/null; do
    [ "$noted" -eq 1 ] || { say "$LANE: shared host lock $HOSTLOCK busy ($(cat "$HOSTLOCK/owner" 2>/dev/null)); waiting for it"; noted=1; }
    wait_guarded "while the shared host lock stayed busy"
  done
  HOST_OWNED=1; trap lane_exit EXIT
  deadline_guard "as the shared host lock was taken"
  echo "$$ $LANE $(date -u +%FT%TZ)" > "$HOSTLOCK/owner"
  say "$LANE holds the host lock (pid $$)"
}
# The host lock is taken FIRST and held while the legacy peers are waited out.  The other order would reopen the
# race: a peer can be armed in the instant between "legacy clear" and the mkdir.
# LEGACY PEERS.  Jobs written before the host lock (the runPV1..runPV6 corpus stores) take /root/.claude-datagen.lock
# and know nothing about this one, so they are waited out separately -- but ONLY while such a job is actually RUNNING,
# which is exactly what holding its lock means.  Never wait on a merely ARMED peer: a legacy store's own gate waits for
# this lane's supervisor to be gone, so two "wait for the armed other" rules would wait on each other forever.
# Holding the host lock through this wait cannot deadlock, because legacy jobs never wait on the host lock.
# Delete this block once no pre-host-lock job can be armed on the box.
legacy_processes_running () { ps -eo stat,args | awk '$1 !~ /^T/' | grep -qE "$LEGACY_PS_RE"; }
wait_legacy_peers () {
  while [ -d "$DATAGEN" ] || [ -d "$LEGACY" ]; do wait_guarded "while a legacy lock stayed present"; done
  while legacy_processes_running; do wait_guarded "while a legacy process stayed alive"; done
  deadline_guard "as the legacy peers cleared"
}
# Compatibility marker: legacy stores gate on this directory, so hold it for this lane's whole life (rule 5: checked).
take_legacy_marker () {
