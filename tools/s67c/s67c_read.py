def armed_line_gate(status, trusted):
    """Exactly one armed line in the status, naming the trusted launcher sha256 and the trusted tree + head: the status is the one the
    reviewed launcher wrote (reader_lib.terminal_line, in bind, then checks the terminal and the failure markers)."""
    lines = open(status, encoding="utf-8").read().split("\n")[:-1]
    armed = re.compile(rl.TS + " " + re.escape(f"{LANE} armed (pid ") + r"\d+" + re.escape(f", launcher sha256 {trusted['launcher_sha256']}): tree {TREE} {TREE_HEAD}; waiting for the RELEASE token ") + ".*")
    n = sum(1 for x in lines if armed.fullmatch(x))
    other = sum(1 for x in lines if f" {LANE} armed (pid " in x)
    if n != 1 or other != 1:
        refuse(f"status: {n} armed lines naming the trusted launcher sha256 {trusted['launcher_sha256'][:12]}... and tree {TREE} @ {TREE_HEAD[:8]} (need exactly one; {other} armed lines in all)")
    return n


def bind_lane(root, status, reservation, *, manifest=None, manifest_sha256=None, trusted=TRUSTED):
    """The lane read's first step, BEFORE any raw read: reader_lib.bind_inputs (host mode: root / status / reservation are canonical,
    absolute, non-symlink paths EQUAL to the trusted dispatch paths, and the reservation names this lane, the trusted launcher sha256, the
    trusted status and root; archive mode: a host-origin manifest at its sha, every copied file reproduced), then <root>/SHA256SUMS as a
    canonical regular file under the bound root, then the armed line (the trusted launcher sha256 and tree).  A TO_BE_PINNED trusted
    launcher (the draft reader) refuses: only the pinned reader reads a lane."""
    if not re.fullmatch(r"[0-9a-f]{64}", trusted["launcher_sha256"]):
        refuse("the reader's trusted launcher sha256 is not pinned (TO_BE_PINNED: the draft reader never reads a lane; make_s67c_final.py pins it at the pin step)")
    try:
        b = rl.bind_inputs(root, status, reservation, trusted=trusted, manifest=manifest, manifest_sha256=manifest_sha256)
        sums = rl._canonical(os.path.join(b["root"], "SHA256SUMS"), "SHA256SUMS", "file")
    except rl.ReaderRefusal as e:
        refuse(str(e))
    b["sums"] = sums
    b["trusted"] = dict(trusted)
    b["armed_lines"] = armed_line_gate(b["status"], trusted)
    return b


def analyze_lane(root, status, reservation, *, manifest=None, manifest_sha256=None, trusted=TRUSTED):
    """The lane read: bind the reserved inputs first (bind_lane), then every arm of ARM_ORDER at <root>/<arm>/duel.jsonl, each analyzed
    alone (any refusal refuses the read).  Nothing under the root is opened before bind_lane returns."""
    b = bind_lane(root, status, reservation, manifest=manifest, manifest_sha256=manifest_sha256, trusted=trusted)
    return {arm: analyze(os.path.join(b["root"], arm, "duel.jsonl"), arm=arm, status=b["status"], sums=b["sums"], binding=b) for arm in ARM_ORDER}


