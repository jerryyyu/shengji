            ("sc8p entered = probes with a positive margin", t["entered"], sum(1 for m in t["margins"] if m > 0)),
            ("sc8p entered = entered by kind", t["entered"], [t["entered_by_kind"][k] for k in KINDS]),
            ("sc8p chosen = chosen by kind", t["chosen"], [t["chosen_by_kind"][k] for k in KINDS]),
            ("sc8p chosen by added kind = chosen by played kind", [t["chosen_by_kind"][k] for k in KINDS], [t["chosen_played_kind"][k] for k in KINDS_PLAYED]),
            ("sc8p leads = leads by played kind", t["leads"], [t["leads_by_played_kind"][k] for k in KINDS_PLAYED]),
